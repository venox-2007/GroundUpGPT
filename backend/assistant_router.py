"""Deterministic assistant routing layer for GroundUpGPT.

Classifies user requests using conservative, deterministic rules to decide execution paths:
- "neural": Pure autoregressive language model generation.
- "safe_calculator": AST-restricted deterministic arithmetic evaluation.
- "local_fact": Curated, versioned fact retrieval with domain-aware entity/relation validation.
- "tool_error": Safe handling of invalid math, syntax errors, or inventory limitations.

Never asks the weak language model to select or evaluate tools.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
import logging
import re
from typing import Any, Dict, List, Optional, Sequence, Tuple

from src.safe_calculator import calculate, CalculationResult
from src.local_fact_retrieval import (
    FACT_INVENTORY,
    FactRecord,
    LocalFactRetriever,
    tokenize_text,
)

logger = logging.getLogger(__name__)

# Accepted execution origins
ORIGIN_NEURAL = "neural"
ORIGIN_SAFE_CALCULATOR = "safe_calculator"
ORIGIN_LOCAL_FACT = "local_fact"
ORIGIN_TOOL_ERROR = "tool_error"
ORIGIN_DOCUMENT_EXCERPT = "document_excerpt"
ORIGIN_GROUNDED_NEURAL = "grounded_neural"
VALID_ORIGINS = {
    ORIGIN_NEURAL,
    ORIGIN_SAFE_CALCULATOR,
    ORIGIN_LOCAL_FACT,
    ORIGIN_TOOL_ERROR,
    ORIGIN_DOCUMENT_EXCERPT,
    ORIGIN_GROUNDED_NEURAL,
}

# Supported chat modes
MODE_NATIVE = "native"
MODE_ASSISTED = "assisted"
VALID_MODES = {MODE_NATIVE, MODE_ASSISTED}

# Curated facts inventory excluding synthetic testing records
CURATED_FACTS: List[FactRecord] = [
    f for f in FACT_INVENTORY if getattr(f, "category", "") != "synthetic"
]

# Supported capital-city lookup entities and fact IDs
SUPPORTED_CAPITAL_COUNTRIES: Dict[str, str] = {
    "france": "geo_france_capital",
    "french": "geo_france_capital",
    "germany": "geo_germany_capital",
    "german": "geo_germany_capital",
    "japan": "geo_japan_capital",
    "japanese": "geo_japan_capital",
    "australia": "geo_australia_capital",
    "australian": "geo_australia_capital",
    "canada": "geo_canada_capital",
    "canadian": "geo_canada_capital",
    "italy": "geo_italy_capital",
    "italian": "geo_italy_capital",
    "spain": "geo_spain_capital",
    "spanish": "geo_spain_capital",
}

CAPITAL_QUERY_RE = re.compile(
    r"\b(?:capitals?|what(?:'s|\s+is|\s+are)\s+(?:the\s+)?capitals?|which\s+(?:city\s+is|cities\s+are)(?:\s+the)?\s+capitals?)\b",
    re.IGNORECASE,
)

NON_CAPITAL_RELATIONS = [
    "population",
    "people",
    "area",
    "size",
    "president",
    "prime minister",
    "leader",
    "currency",
    "language",
    "gdp",
    "economy",
    "flag",
    "anthem",
    "weather",
    "food",
]


@dataclass
class AssistantRouteDecision:
    """Structured routing decision produced by the assistant router.

    Attributes:
        origin: One of 'neural', 'safe_calculator', 'local_fact', 'tool_error'.
        mode: Active mode ('native' or 'assisted').
        model_generated: Whether the final answer text is generated by neural weights.
        is_terminal: True if decision provides immediate result without model inference.
        answer_text: Complete text of tool result or error message if terminal.
        tool_name: Human-readable name of deterministic tool if used.
        fact_id: Unique record ID of retrieved local fact if applicable.
        provenance: Stored origin of fact record if applicable.
        evaluated_expression: Normalized arithmetic expression if evaluated.
        error_code: Specific error code for tool failures or inventory limitations.
        details: Additional structured metadata for transparency.
    """

    origin: str
    mode: str
    model_generated: bool
    is_terminal: bool
    answer_text: Optional[str] = None
    tool_name: Optional[str] = None
    fact_id: Optional[str] = None
    provenance: Optional[str] = None
    evaluated_expression: Optional[str] = None
    error_code: Optional[str] = None
    details: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class AssistantRouter:
    """Server-side deterministic router selecting appropriate execution engines."""

    def __init__(self, fact_inventory: Optional[Sequence[FactRecord]] = None) -> None:
        if fact_inventory is None:
            # Strictly filter out synthetic test facts from public assistant router
            self.fact_inventory: List[FactRecord] = [
                f for f in FACT_INVENTORY if getattr(f, "category", "") != "synthetic"
            ]
        else:
            self.fact_inventory = list(fact_inventory)

        self.retriever = LocalFactRetriever(inventory=self.fact_inventory)
        self._fact_by_id = {f.fact_id: f for f in self.fact_inventory}

    def classify_and_route(self, prompt: str, mode: str = MODE_NATIVE) -> AssistantRouteDecision:
        """Route user query deterministically.

        Args:
            prompt: User message text.
            mode: 'native' (default) or 'assisted'.

        Returns:
            AssistantRouteDecision specifying target origin and result if terminal.

        Raises:
            ValueError: If mode is not strictly 'native' or 'assisted'.
        """
        if mode not in VALID_MODES:
            raise ValueError(f"Invalid mode '{mode}'. Must be strictly 'native' or 'assisted'.")

        prompt_clean = prompt.strip()

        # In native mode, all requests are routed to the neural model
        if mode == MODE_NATIVE:
            return AssistantRouteDecision(
                origin=ORIGIN_NEURAL,
                mode=MODE_NATIVE,
                model_generated=True,
                is_terminal=False,
            )

        # 1. Check for arithmetic calculation intent
        calc_result: CalculationResult = calculate(prompt_clean)
        if calc_result.is_arithmetic_query:
            if calc_result.is_valid:
                return AssistantRouteDecision(
                    origin=ORIGIN_SAFE_CALCULATOR,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text=str(calc_result.result_str),
                    tool_name="SafeCalculator",
                    evaluated_expression=calc_result.extracted_expression,
                    details={"parser_confidence": calc_result.parser_confidence},
                )
            else:
                return AssistantRouteDecision(
                    origin=ORIGIN_TOOL_ERROR,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text=f"SafeCalculator Error: {calc_result.error_message}",
                    tool_name="SafeCalculator",
                    evaluated_expression=calc_result.extracted_expression,
                    error_code=calc_result.error_type or "syntax_error",
                    details={"parser_confidence": calc_result.parser_confidence},
                )

        # 2. Check for domain-aware curated factual queries
        fact_decision = self._route_factual_query(prompt_clean)
        if fact_decision is not None:
            return fact_decision

        # 3. Fallback to neural generation for conversational / creative / uncataloged queries
        return AssistantRouteDecision(
            origin=ORIGIN_NEURAL,
            mode=MODE_ASSISTED,
            model_generated=True,
            is_terminal=False,
        )

    def _route_factual_query(self, prompt: str) -> Optional[AssistantRouteDecision]:
        """Apply domain-aware entity and relation validation for local facts."""
        q_lower = prompt.lower()

        # Check for explicit creative/conversational instructions mentioning factual terms
        # (e.g. "Tell me a story about a whale in Japan" -> route to neural)
        if re.search(r"\b(?:tell\s+me\s+a\s+story|write\s+a\s+story|write\s+a\s+poem|compose|write\s+an\s+essay)\b", q_lower):
            return None

        # --- A. Capital City Queries ---
        if CAPITAL_QUERY_RE.search(q_lower):
            matched_country_fact_ids = []
            for country, fid in SUPPORTED_CAPITAL_COUNTRIES.items():
                if re.search(r"\b" + re.escape(country) + r"\b", q_lower):
                    if fid not in matched_country_fact_ids:
                        matched_country_fact_ids.append(fid)

            # Multi-entity detection: plural "capitals" or conjunctions ("and", "or", ",", "&", "as well as")
            is_plural = bool(re.search(r"\bcapitals\b", q_lower))
            has_conjunction = bool(re.search(r"\b(?:and|or|as\s+well\s+as)\b|[,&]", q_lower))

            # Multiple entities mentioned or conjunction present -> ambiguous query rejection
            if len(matched_country_fact_ids) > 1 or (matched_country_fact_ids and (is_plural or has_conjunction)):
                return AssistantRouteDecision(
                    origin=ORIGIN_LOCAL_FACT,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text="The query mentions multiple countries or asks for multiple capitals. Local fact retrieval requires an unambiguous single-country question.",
                    tool_name="LocalFactRetriever",
                    fact_id=None,
                    provenance="curated_groundup_facts_v1",
                    error_code="ambiguous_query",
                    details={
                        "matched_entities_count": len(matched_country_fact_ids),
                        "is_plural": is_plural,
                        "has_conjunction": has_conjunction,
                    },
                )

            # Exactly one supported country matched
            if len(matched_country_fact_ids) == 1:
                fid = matched_country_fact_ids[0]
                fact = self._fact_by_id[fid]
                return AssistantRouteDecision(
                    origin=ORIGIN_LOCAL_FACT,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text=fact.verified_answer,
                    tool_name="LocalFactRetriever",
                    fact_id=fact.fact_id,
                    provenance=fact.source,
                    details={
                        "entity": fact.entity,
                        "category": fact.category,
                        "supporting_passage": fact.supporting_passage,
                        "version": fact.version,
                    },
                )

            # Capital query asked, but country/entity is NOT in supported inventory
            # (e.g. "What is the capital of Eldoria?", "What is the capital of Jupiter?", "What is the capital of Norway?")
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text="I do not have a verified record for that capital in my local fact inventory. Supported countries are France, Germany, Japan, Australia, Canada, Italy, and Spain.",
                tool_name="LocalFactRetriever",
                fact_id=None,
                provenance="curated_groundup_facts_v1",
                error_code="unsupported_fact",
            )

        # --- B. Non-Capital Country Relations (prevent returning capital for population, etc.) ---
        # e.g., "What is the population of Japan?"
        for country in SUPPORTED_CAPITAL_COUNTRIES:
            if re.search(r"\b" + re.escape(country) + r"\b", q_lower):
                for rel in NON_CAPITAL_RELATIONS:
                    if re.search(r"\b" + re.escape(rel) + r"\b", q_lower):
                        return AssistantRouteDecision(
                            origin=ORIGIN_LOCAL_FACT,
                            mode=MODE_ASSISTED,
                            model_generated=False,
                            is_terminal=True,
                            answer_text=f"I do not have a verified record for the {rel} of that country in my local fact inventory. Supported geographic queries are currently limited to capital cities.",
                            tool_name="LocalFactRetriever",
                            fact_id=None,
                            provenance="curated_groundup_facts_v1",
                            error_code="unsupported_fact",
                        )

        # --- C. Science & Biology Domain Validations ---

        # 1. Water state of matter at room temperature
        if re.search(r"\bwater\b", q_lower) and (
            re.search(r"\broom\s+temperature\b", q_lower)
            or re.search(r"\bstate\s+of\s+matter\b", q_lower)
            or (re.search(r"\bsolid\b", q_lower) and re.search(r"\bliquid\b", q_lower))
        ):
            fact = self._fact_by_id["sci_water_room_temp"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # 2. Wood conductivity
        if re.search(r"\bwood\b", q_lower) and (
            re.search(r"\bconductor\b", q_lower)
            or re.search(r"\binsulator\b", q_lower)
            or re.search(r"\bconduct\s+electricity\b", q_lower)
        ):
            fact = self._fact_by_id["sci_wood_conductivity"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # 3. Iron classification
        if re.search(r"\biron\b", q_lower) and (
            re.search(r"\bmetal\b", q_lower) or re.search(r"\bnon-?metal\b", q_lower)
        ):
            fact = self._fact_by_id["sci_iron_classification"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # 4. Chemical formula for water (and unsupported formulas)
        if re.search(r"\b(?:chemical\s+)?formula\b", q_lower):
            if re.search(r"\bwater\b", q_lower) or re.search(r"\bh2o\b", q_lower):
                fact = self._fact_by_id["sci_chemical_water"]
                return AssistantRouteDecision(
                    origin=ORIGIN_LOCAL_FACT,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text=fact.verified_answer,
                    tool_name="LocalFactRetriever",
                    fact_id=fact.fact_id,
                    provenance=fact.source,
                    details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
                )
            else:
                return AssistantRouteDecision(
                    origin=ORIGIN_LOCAL_FACT,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text="I do not have a verified record for that chemical formula in my local fact inventory. Supported chemical formulas are currently limited to water (H2O).",
                    tool_name="LocalFactRetriever",
                    fact_id=None,
                    provenance="curated_groundup_facts_v1",
                    error_code="unsupported_fact",
                )

        # 5. Chemical symbol for gold (and unsupported symbols)
        if re.search(r"\b(?:chemical\s+symbol|symbol\s+for|symbol\s+of)\b", q_lower):
            if re.search(r"\bgold\b", q_lower):
                fact = self._fact_by_id["sci_gold_symbol"]
                return AssistantRouteDecision(
                    origin=ORIGIN_LOCAL_FACT,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text=fact.verified_answer,
                    tool_name="LocalFactRetriever",
                    fact_id=fact.fact_id,
                    provenance=fact.source,
                    details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
                )
            else:
                return AssistantRouteDecision(
                    origin=ORIGIN_LOCAL_FACT,
                    mode=MODE_ASSISTED,
                    model_generated=False,
                    is_terminal=True,
                    answer_text="I do not have a verified record for that chemical symbol in my local fact inventory. Supported chemical symbols are currently limited to gold (Au).",
                    tool_name="LocalFactRetriever",
                    fact_id=None,
                    provenance="curated_groundup_facts_v1",
                    error_code="unsupported_fact",
                )

        # 6. Speed of light in vacuum
        if re.search(r"\bspeed\s+of\s+light\b", q_lower) or re.search(r"\bhow\s+fast\s+is\s+light\b", q_lower):
            fact = self._fact_by_id["sci_speed_of_light"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # 7. Primary colors
        if re.search(r"\b(?:3|three)?\s*primary\s+colors\b", q_lower):
            fact = self._fact_by_id["sci_primary_colors"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # 8. Whale mammal classification
        if re.search(r"\bwhales?\b", q_lower) and (
            re.search(r"\bmammal\b", q_lower) or re.search(r"\bfish\b", q_lower)
        ):
            fact = self._fact_by_id["bio_whale_mammal"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # 9. Photosynthesis organelle
        if re.search(r"\bphotosynthesis\b", q_lower) and (
            re.search(r"\borganelle\b", q_lower) or re.search(r"\bcell\b", q_lower) or re.search(r"\bwhere\b", q_lower)
        ):
            fact = self._fact_by_id["bio_photosynthesis_organelle"]
            return AssistantRouteDecision(
                origin=ORIGIN_LOCAL_FACT,
                mode=MODE_ASSISTED,
                model_generated=False,
                is_terminal=True,
                answer_text=fact.verified_answer,
                tool_name="LocalFactRetriever",
                fact_id=fact.fact_id,
                provenance=fact.source,
                details={"entity": fact.entity, "category": fact.category, "supporting_passage": fact.supporting_passage},
            )

        # Not recognized as a targeted factual query
        return None


# Global singleton instance of assistant router
assistant_router = AssistantRouter()
